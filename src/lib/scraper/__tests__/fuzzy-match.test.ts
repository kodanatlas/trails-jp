import { describe, expect, it } from "vitest";
import { fuzzyMatch, normalize } from "../lapcenter";

describe("fuzzyMatch: JOY と LapCenter の恒常的な表記差", () => {
  it.each([
    ["霧ヶ峰ミドルO", "霧ヶ峰ミドルオリエンテーリング2025"],
    ["彩の森入間公園OL体験会＆併設ロゲ", "第45回(11月度) 入間市OLCオリエンテーリング体験会"],
    ["大阪OLC", "大阪オリエンテーリングクラブ"],
    // 西暦除去後の core は2文字。下限を3に戻すと実データで17件規模の突合を失う回帰番人。
    ["岩手大会2025 Day1", "岩手オリエンテーリング大会2025Day1スプリント"],
    ["長岡OLCフィジカル練習会", "長岡OLC練習会"],
    ["ES関東C壮行会", "ES関東C日本代表壮行会"],
    // 「日本」を先に消すと残骸「代表」が識別部分の途中に挟まり、core の包含が崩れる回帰番人。
    ["ES関東C壮行会", "ES日本代表関東C壮行会"],
    [
      "金沢市民オリエンテーリング大会",
      "（令和８年度）第69回金沢市民スポーツ大会オリエンテーリング競技",
    ],
    [
      "中高選手権　団体オープン競技",
      "第40回全国中学校高等学校オリエンテーリング選手権大会",
    ],
    [
      "彩の森入間公園OL体験会＆併設ロゲ",
      "第55回(26年度7月度) 入間市オリエンテーリング体験会",
    ],
  ])("%s と %s を同一大会と判定する", (joyName, lapCenterName) => {
    expect(fuzzyMatch(joyName, lapCenterName)).toBe(true);
  });

  it.each([
    [
      "第49回霧ヶ峰オリエンテーリング大会",
      "（令和８年度）第78回石川県民スポーツ大会オリエンテーリング競技",
    ],
    ["千葉大OLC 技術局練習会", "入間市OLC夏合宿 Day2"],
    [
      "金沢市民オリエンテーリング大会",
      "（令和８年度）第78回石川県民スポーツ大会オリエンテーリング競技",
    ],
    // 会場名 alias の境界。単に「入間市」へ潰すと core が市名だけになり、同市の無関係な
    // イベントに包含されて誤突合した。「入間市彩の森」に変えてこれを塞いだので、その回帰番人。
    ["彩の森入間公園OL大会", "入間市OLC夏合宿 Day2"],
  ])("%s と %s を別大会と判定する", (joyName, lapCenterName) => {
    expect(fuzzyMatch(joyName, lapCenterName)).toBe(false);
  });

  // 中高選手権 alias の既知の限界を、期待値として明示的に固定する。
  // 本大会名は core が「中学校高等学校」と短く汎用的なため、これを含む名前は何でも当たる。
  // alias を狭めると本命の「団体オープン競技」（LC 側が接尾辞なし）も落ちるので分離できない。
  // 突合は同日限定なので、同日開催でなければ実害は出ない（2019〜2026 の全件検証で衝突ゼロ）。
  // ここを false に変えたくなったら、まず「団体オープン競技」が当たり続けるか確認すること。
  it("既知の限界: 中高選手権 alias は本大会以外の同名接頭辞にも当たる", () => {
    expect(
      fuzzyMatch("中高選手権対策&新人練習会", "第37回全国中学校高等学校オリエンテーリング選手権大会"),
    ).toBe(true);
  });
});

describe("normalize: 日付と裸の西暦の除去順", () => {
  it("8桁日付を先に除去し、月日の残骸を残さない", () => {
    const normalized = normalize("20250126-みえスポーツフェスティバル2024");
    expect(normalized).not.toContain("0126");
    expect(normalized).toBe("みえスポーツフェスティバル");
  });
});
